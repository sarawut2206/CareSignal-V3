/* ============================================================
   cs-roi.js — เครื่องคำนวณจุดคุ้มทุนของบริการป้องกัน (สำหรับบริษัทประกัน)
   ------------------------------------------------------------
   ทำไมต้องมี: สไลด์เดิมคิดว่า "การล้มที่ป้องกันได้ทุกครั้ง = ค่าสินไหมหลักแสน"
   ซึ่งสูงเกินจริง เพราะการล้มส่วนใหญ่ไม่ได้ทำให้ต้องนอนโรงพยาบาล
   ข้อมูลกรมควบคุมโรค ปี 2567: ผู้ป่วยในจากหกล้ม 661 ต่อประชากรผู้สูงอายุแสนคน
   = 6.6 รายต่อ 1,000 คนต่อปี ซึ่งเป็นราว 2% ของการล้มทั้งหมด (ล้มปีละ ~1 ใน 3)

   เครื่องมือนี้จึงไม่บอกว่า "คุ้ม" หรือ "ไม่คุ้ม" แต่ให้บริษัทประกันใส่ตัวเลขพอร์ตตัวเอง
   แล้วคืนค่าที่ตรวจสอบได้: ป้องกันได้กี่ราย ประหยัดเท่าไร และต้องได้ผลแค่ไหนจึงจะคุ้ม
   ตัวเลขตั้งต้นทุกตัวมีที่มากำกับ และสิ่งที่เป็นสมมติฐานติดป้ายไว้ชัดเจน
   ============================================================ */
(function (g) {
  /* ค่าตั้งต้นจากข้อมูลจริง — ผู้ใช้แก้ได้ทุกช่อง */
  var DEF = {
    members: 1000,          /* จำนวนผู้เอาประกันสูงอายุในโครงการ */
    pmpm: 99,               /* ค่าบริการต่อคนต่อเดือน (บาท) */
    admitPer1000: 6.6,      /* ล้มแล้วต้องนอนโรงพยาบาล ต่อ 1,000 คน/ปี — กรมควบคุมโรค 2567 */
    opdPer1000: 32.8,       /* ล้มแล้วมาผู้ป่วยนอก ต่อ 1,000 คน/ปี — กรมควบคุมโรค 2567 */
    costAdmit: 150000,      /* ค่าสินไหมเฉลี่ยต่อการนอนโรงพยาบาล 1 ครั้ง (บาท) — ใส่ของพอร์ตจริง */
    costOpd: 5000,          /* ค่าสินไหมเฉลี่ยต่อการรักษาแบบผู้ป่วยนอก 1 ครั้ง (บาท) */
    effect: 23,             /* สมมติฐานลดอัตราการล้ม (%) — Cochrane 2019 เป็นผลของโปรแกรมออกกำลังกาย */
    reach: 100              /* สัดส่วนสมาชิกที่ใช้บริการจริงและทำตามคำแนะนำ (%) */
  };
  var SRC = {
    rate: "อัตราผู้ป่วยในและผู้ป่วยนอกจากการพลัดตกหกล้ม ปี 2567 · กองป้องกันการบาดเจ็บ กรมควบคุมโรค (ไม่รวมกรุงเทพมหานคร)",
    effect: "Sherrington C, et al. Cochrane Database of Systematic Reviews 2019 — โปรแกรมออกกำลังกายลดอัตราการล้มราว 23% · ไม่ใช่ผลของการคัดกรองเพียงอย่างเดียว",
    cost: "ค่าสินไหมเป็นตัวเลขที่บริษัทประกันใส่เอง · ค่าตั้งต้น 150,000 บาทเป็นสมมติฐาน ส่วนค่ารักษาเฉลี่ยที่รัฐเบิกจริงปี 2567 อยู่ที่ 23,410 บาทต่อราย",
    program: "เกณฑ์ภายในโปรแกรม CareSignal — ใช้วางแผน ยังไม่ใช่ผลที่พิสูจน์แล้ว"
  };
  function num(v, d) { v = typeof v === "string" ? parseFloat(v.replace(/,/g, "")) : v; return isFinite(v) && v >= 0 ? v : d; }

  /* คืนค่าที่ตรวจสอบได้ทุกบรรทัด — ไม่มีตัวเลขไหนที่ย้อนวิธีคิดไม่ได้ */
  function calc(inp) {
    inp = inp || {};
    var m = num(inp.members, DEF.members), pmpm = num(inp.pmpm, DEF.pmpm);
    var aR = num(inp.admitPer1000, DEF.admitPer1000), oR = num(inp.opdPer1000, DEF.opdPer1000);
    var cA = num(inp.costAdmit, DEF.costAdmit), cO = num(inp.costOpd, DEF.costOpd);
    var eff = num(inp.effect, DEF.effect) / 100, reach = num(inp.reach, DEF.reach) / 100;
    var fee = m * pmpm * 12;                                   /* ค่าบริการที่บริษัทจ่ายต่อปี */
    var admits = m / 1000 * aR, opds = m / 1000 * oR;          /* เหตุที่คาดว่าจะเกิดใน 1 ปี */
    var cutA = admits * eff * reach, cutO = opds * eff * reach; /* เหตุที่ป้องกันได้ */
    var saved = cutA * cA + cutO * cO;
    var net = saved - fee, ratio = fee > 0 ? saved / fee : 0;
    /* ต้องลดเหตุได้กี่ % จึงจะเท่าทุน (ที่ค่าสินไหมและ reach ที่ใส่มา) */
    var perEvent = (admits * cA + opds * cO) * reach;
    var needEffect = perEvent > 0 ? fee / perEvent * 100 : null;
    /* ถ้าคงผลที่ eff ไว้ ค่าสินไหมต่อการนอนโรงพยาบาลต้องเท่าไรจึงจะเท่าทุน */
    var needCostAdmit = cutA > 0 ? (fee - cutO * cO) / cutA : null;
    return {
      fee: fee, admits: admits, opds: opds, cutAdmits: cutA, cutOpds: cutO, saved: saved, net: net, ratio: ratio,
      needEffect: needEffect, needCostAdmit: needCostAdmit,
      breakeven: net >= 0,
      /* ข้อความที่พูดได้ตรง ๆ โดยไม่ต้องตีความ */
      verdict: net >= 0
        ? "ที่ตัวเลขชุดนี้ ค่าสินไหมที่ประหยัดได้มากกว่าค่าบริการ " + (Math.round(ratio * 100) / 100) + " เท่า"
        : "ที่ตัวเลขชุดนี้ ยังไม่คุ้มด้วยค่าสินไหมอย่างเดียว — ต้องลดเหตุให้ได้ราว " + (needEffect == null ? "—" : Math.round(needEffect) + "%") +
          " หรือค่าสินไหมต่อการนอนโรงพยาบาลต้องสูงกว่า " + (needCostAdmit == null || needCostAdmit < 0 ? "—" : Math.round(needCostAdmit).toLocaleString("th-TH") + " บาท") +
          " จึงจะเท่าทุน (ยังไม่นับมูลค่าด้านการรักษาลูกค้าและการชะลอภาวะพึ่งพิง)"
    };
  }
  var API = { DEF: DEF, SRC: SRC, calc: calc };
  g.CSRoi = API;
  if (typeof module !== "undefined" && module.exports) module.exports = API;
})(typeof window !== "undefined" ? window : this);
